async function buildExternalBundle(outDir, generatedModules, stamp) {
  fs.mkdirSync(outDir, { recursive: true });

  const temporaryFile = `trusted-prebid-${process.pid}-${crypto.randomUUID()}.tmp.js`;
  const temporaryPath = path.join(outDir, temporaryFile);
  let renamedTemporaryFile = false;

  try {
    const { build } = await import('vite');

    await build({
      configFile: false,
      root: __dirname,
      resolve: {
        alias: [
          { find: ADAPTERS_GENERATED_SPECIFIER, replacement: generatedModules.adaptersFile },
          { find: USER_IDS_GENERATED_SPECIFIER, replacement: generatedModules.userIdsFile },
          { find: LIVE_INTENT_SHIM_ALIAS, replacement: LIVE_INTENT_SHIM },
          { find: 'prebid.js/modules/liveIntentIdSystem', replacement: LIVE_INTENT_SHIM },
          {
            find: 'tsjs-prebid/liveIntentIdSystemStandard',
            replacement: PREBID_LIVE_INTENT_STANDARD,
          },
          { find: 'tsjs-prebid/prebidGlobal', replacement: PREBID_GLOBAL_MODULE },
          {
            find: 'prebid.js/src/adapterManager.js',
            replacement: path.resolve(
              __dirname,
              'node_modules/prebid.js/dist/src/src/adapterManager.js'
            ),
          },
          {
            find: 'prebid.js/src/adRendering.js',
            replacement: path.resolve(
              __dirname,
              'node_modules/prebid.js/dist/src/src/adRendering.js'
            ),
          },
        ],
      },
      build: {
        emptyOutDir: false,
        outDir,
        assetsDir: '.',
        sourcemap: false,
        minify: 'esbuild',
        rollupOptions: {
          input: generatedModules.entryFile,
          output: {
            format: 'iife',
            dir: outDir,
            entryFileNames: temporaryFile,
            extend: false,
            name: 'tsjs_prebid_external',
          },
        },
      },
      logLevel: 'warn',
    });

    const unwrappedBundle = fs.readFileSync(temporaryPath, 'utf8');
    const normalizedBundle = renderExternalWrapper(unwrappedBundle, stamp);
    const sentinelCount = normalizedBundle.split(ARTIFACT_RELEASE_SENTINEL).length - 1;
    if (sentinelCount !== 1) {
      throw new Error(
        `[build-prebid-external] Expected one artifact release sentinel, found ${sentinelCount}`
      );
    }
    const artifactReleaseId = sha256Hex(Buffer.from(normalizedBundle, 'utf8'));
    const finalBundle = normalizedBundle.replace(ARTIFACT_RELEASE_SENTINEL, artifactReleaseId);
    if (finalBundle.includes(ARTIFACT_RELEASE_SENTINEL)) {
      throw new Error('[build-prebid-external] Artifact release sentinel remained after stamping');
    }
    const bundleBytes = Buffer.from(finalBundle, 'utf8');
    const metadata = deriveBundleMetadata(bundleBytes);
    const finalPath = path.join(outDir, metadata.filename);

    fs.rmSync(finalPath, { force: true });
    fs.writeFileSync(finalPath, bundleBytes);
    fs.rmSync(temporaryPath, { force: true });
    renamedTemporaryFile = true;

    return { ...metadata, artifactReleaseId };
  } finally {
    if (!renamedTemporaryFile) {
      fs.rmSync(temporaryPath, { force: true });
    }
  }
}

export async function main(argv = process.argv.slice(2)) {
  const args = parseArgs(argv);
  const generatedModules = createTemporaryModulePaths();

  try {
    const adapters = generateAdapterImports(args.adapters, generatedModules.adaptersFile);
    const adapterMetadata = readAdapterMetadata(adapters);
    const userIdModules = generateUserIdImports(args.userIdModules, generatedModules.userIdsFile);
    generateExternalEntry(generatedModules.entryFile);
    const version = prebidPackageVersion();
    if (version !== EXPECTED_PREBID_VERSION) {
      throw new Error(
        `[build-prebid-external] Expected Prebid.js ${EXPECTED_PREBID_VERSION}, found ${version}`
      );
    }
    const moduleStems = [
      ...new Set([...adapters, ...userIdModules.map(({ moduleName }) => moduleName)]),
    ].sort();
    const stamp = {
      abi: 1,
      artifactReleaseId: ARTIFACT_RELEASE_SENTINEL,
      prebidVersion: EXPECTED_PREBID_VERSION,
      moduleStems,
      bidderCodes: adapterMetadata.bidderCodes,
      bidderAliases: adapterMetadata.bidderAliases,
      userIdModules,
    };
    const bundle = await buildExternalBundle(args.outDir, generatedModules, stamp);
    const manifest = {
      ...stamp,
      artifactReleaseId: bundle.artifactReleaseId,
      sha256: bundle.sha256,
      sri: bundle.sri,
      filename: bundle.filename,
    };

    fs.writeFileSync(
      path.join(args.outDir, 'manifest.json'),
      `${JSON.stringify(manifest, null, 2)}\n`
    );

    console.log('[build-prebid-external] Built external Prebid bundle:', bundle.filename);
    console.log('[build-prebid-external] SHA-256:', bundle.sha256);
    console.log('[build-prebid-external] SRI:', bundle.sri);
    console.log('[build-prebid-external] Manifest:', path.join(args.outDir, 'manifest.json'));
  } finally {
    fs.rmSync(generatedModules.temporaryDir, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await main();
}
