//! Build script for `trusted-server-adapter-fastly`: lists core's Rust sources
//! for the test that checks core never uses the Fastly SDK.

#![allow(
    clippy::print_stdout,
    reason = "Cargo build scripts communicate rebuild inputs on stdout"
)]

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("should read CARGO_MANIFEST_DIR"));
    let src_dir = manifest_dir
        .parent()
        .expect("should have the crates folder above this crate")
        .join("trusted-server-core")
        .join("src");

    // Cargo walks a directory named here, so adding, renaming or deleting a
    // core source file reruns this script and the list follows the tree.
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", path_literal(&src_dir));

    // A checkout without core's sources builds with an empty list, which the
    // test that pins the list to core's tree refuses.
    let mut sources = Vec::new();
    if src_dir.is_dir() {
        collect_rust_sources(&src_dir, &src_dir, &mut sources);
    }
    sources.sort();

    let mut generated = String::from(
        "// Generated by build.rs. Every Rust source file under core's `src`.\n\
         const CHECKED_SOURCES: &[(&str, &str)] = &[\n",
    );
    for relative in &sources {
        let absolute = format!("{}/{relative}", path_literal(&src_dir));
        generated.push_str(&format!(
            "    (\"{relative}\", include_str!(\"{absolute}\")),\n"
        ));
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("should read OUT_DIR"));
    fs::write(out_dir.join("core_sources.rs"), generated)
        .expect("should write the core source list");
}

/// Collects every `.rs` file under `dir`, as a path relative to `root` with
/// forward slashes, so the generated file reads the same on every platform.
fn collect_rust_sources(root: &Path, dir: &Path, sources: &mut Vec<String>) {
    let entries = fs::read_dir(dir).expect("should read a source directory");
    for entry in entries {
        let entry = entry.expect("should read a source directory entry");
        let path = entry.path();
        if path.is_dir() {
            collect_rust_sources(root, &path, sources);
            continue;
        }
        if path.extension().is_some_and(|extension| extension == "rs") {
            let relative = path
                .strip_prefix(root)
                .expect("should strip the source root prefix");
            sources.push(path_literal(relative));
        }
    }
}

/// Renders a path for a Rust string literal, with forward slashes so a Windows
/// path needs no escaping.
fn path_literal(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}
