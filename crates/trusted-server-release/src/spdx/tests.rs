#[test]
fn normal_and_build_dependencies_preserve_direction_and_reject_duplicates() {
    let mut inputs = fixture();
    inputs.dependencies = vec![
        Dependency {
            from: "rust:example".to_owned(),
            to: "native:example".to_owned(),
            build: false,
        },
        Dependency {
            from: "rust:example".to_owned(),
            to: "tool:example".to_owned(),
            build: true,
        },
    ];
    let first = render(&inputs).expect("should render normal and build dependency edges");
    let doc: Value =
        serde_json::from_slice(first.bytes()).expect("should parse dependency document");
    let parent = package(&doc, "rust:example")["SPDXID"]
        .as_str()
        .expect("should identify parent package");
    let dependency = package(&doc, "native:example")["SPDXID"]
        .as_str()
        .expect("should identify ordinary dependency");
    let build = package(&doc, "tool:example")["SPDXID"]
        .as_str()
        .expect("should identify build dependency");
    assert!(
        relation(&doc, parent, "DEPENDS_ON", dependency),
        "should point normal dependency from parent to dependency"
    );
    assert!(
        relation(&doc, build, "BUILD_DEPENDENCY_OF", parent),
        "should point build dependency toward its consuming parent"
    );
    inputs.dependencies.reverse();
    assert_eq!(
        first.bytes(),
        render(&inputs)
            .expect("should render reordered dependencies")
            .bytes(),
        "should sort dependency relationships independently of input order"
    );
    inputs.dependencies.push(Dependency {
        from: "rust:example".to_owned(),
        to: "native:example".to_owned(),
        build: false,
    });
    assert!(
        render(&inputs).is_err(),
        "should reject duplicate dependency edges"
    );
}

