# shellcheck shell=bash
# Shared helpers for the documentation proposal scripts. Source this file;
# do not execute it.

DOCS_PROPOSAL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOCS_PROPOSAL_ALLOWED_RE='^docs/(guide/.+|index\.md)$'
DOCS_PROPOSAL_MAX_RATIONALE_BYTES=20000

# The branch proposals are made for and opened against; defaults to main.
DOCS_PROPOSAL_BRANCH="${DOCS_PROPOSAL_BRANCH:-main}"

# Exits unless the argument is a full commit SHA reachable from the branch.
docs_proposal_require_sha() {
  local sha="$1"
  if ! [[ "$sha" =~ ^[0-9a-f]{40}$ ]]; then
    printf '::error::Expected a full 40-character commit SHA, got %s\n' "$sha" >&2
    exit 1
  fi
  if ! git merge-base --is-ancestor "$sha" "origin/$DOCS_PROPOSAL_BRANCH" 2>/dev/null; then
    printf '::error::Commit %s is not reachable from origin/%s\n' "$sha" "$DOCS_PROPOSAL_BRANCH" >&2
    exit 1
  fi
}

# Prints the proposal branch for <sha>. Proposals for `main` keep the
# `docs/auto/<sha12>` name; other branches add a hash of the branch name, so a
# commit on several branches gets one proposal per branch.
docs_proposal_branch() {
  local branch_hash
  if [ "$DOCS_PROPOSAL_BRANCH" = main ]; then
    printf 'docs/auto/%s\n' "${1:0:12}"
  else
    branch_hash="$(printf '%s' "$DOCS_PROPOSAL_BRANCH" | git hash-object --stdin)"
    printf 'docs/auto/%s/%s\n' "${branch_hash:0:12}" "${1:0:12}"
  fi
}

# Reads changed paths on stdin, prints those outside the allowlist, and
# returns 1 when any were found.
docs_proposal_disallowed_paths() {
  local path
  local found=0
  while IFS= read -r path; do
    if [ -n "$path" ] && ! [[ "$path" =~ $DOCS_PROPOSAL_ALLOWED_RE ]]; then
      printf '%s\n' "$path"
      found=1
    fi
  done
  return "$found"
}

# Applies <patch> to the index on a detached checkout of <sha>, then exits
# when it changes paths outside the allowlist or entries that are not regular
# files.
docs_proposal_apply() {
  local sha="$1"
  local patch="$2"
  local disallowed
  git switch --quiet --detach "$sha"
  git apply --index "$patch"
  if ! disallowed="$(git diff --cached --name-only --no-renames "$sha" | docs_proposal_disallowed_paths)"; then
    printf '::error::Proposal changes paths outside docs/guide/** and docs/index.md:\n%s\n' "$disallowed"
    exit 1
  fi
  # A symlink passes the path check, but VitePress builds and publishes its
  # target, so a proposal may only add, edit, or delete regular files.
  disallowed="$(git diff --cached --raw --no-renames "$sha" | awk '$2 != "100644" && $2 != "000000"')"
  if [ -n "$disallowed" ]; then
    printf '::error::Proposal changes entries that are not regular files:\n%s\n' "$disallowed"
    exit 1
  fi
}

docs_proposal_pr_body() {
  local sha="$1"
  local base="$2"
  local subject="$3"
  local origin_pr="$4"
  local rationale="$5"
  local origin=""
  if [ -n "$origin_pr" ]; then
    origin=" (#$origin_pr)"
  fi
  printf '<!-- docs-proposal: %s -->\n' "$sha"
  printf '<!-- docs-proposal-base: %s -->\n' "$base"
  printf 'Proposed documentation update for changes through %s%s: %s\n\n' "$sha" "$origin" "$subject"
  printf 'Copilot inspected %s..%s.\n\n' "${base:0:12}" "${sha:0:12}"
  printf 'Generated by GitHub Copilot CLI in the docs-proposal workflow. A maintainer must verify every hunk against the merged code before merging. The review on this pull request lists the source Copilot cited for each hunk and how to revert it.\n\n'
  printf '## Rationale\n\n'
  if [ -s "$rationale" ]; then
    # The rationale is model output; render it inert so it cannot ping users,
    # reference or close issues, or embed links, images, or HTML.
    head -c "$DOCS_PROPOSAL_MAX_RATIONALE_BYTES" "$rationale" \
      | node "$DOCS_PROPOSAL_DIR/hunks.mjs" rationale
  else
    printf '_Copilot did not provide a rationale._\n'
  fi
}
