const outputs = [
  [es5Path, es5Output],
  [bootstrapPath, bootstrapOutput],
  [typescriptPath, typescriptOutput],
  [documentValidatorPath, documentValidatorOutput],
];
const checkOnly = process.argv.slice(2).includes("--check");

if (checkOnly) {
  const stale = [];
  for (const [outputPath, expected] of outputs) {
    let actual;
    try {
      actual = await readFile(outputPath, "utf8");
    } catch {
      stale.push(path.relative(repositoryRoot, outputPath));
      continue;
    }
    if (actual !== expected)
      stale.push(path.relative(repositoryRoot, outputPath));
  }
  if (stale.length > 0) {
    throw new Error("stale APS renderer contract output: " + stale.join(", "));
  }
} else {
  for (const [outputPath, output] of outputs) {
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, output);
  }
}
