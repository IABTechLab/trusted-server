function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

invariant(
  schema?.properties?.type?.const === "aps",
  "schema type should be aps",
);
invariant(
  schema?.properties?.version?.const === 1,
  "schema version should be 1",
);
invariant(
  schema?.properties?.width?.minimum === 1 &&
    schema?.properties?.height?.minimum === 1,
  "schema minimum dimensions should be 1",
);
invariant(
  schema?.properties?.width?.maximum === 4096 &&
    schema?.properties?.height?.maximum === 4096,
  "schema maximum dimensions should be 4096",
);
invariant(
  schema?.properties?.aaxResponse?.["x-decodedMaxBytes"] === 262144,
  "schema decoded AAX limit should be 256 KiB",
);
invariant(corpus?.schemaVersion === 1, "corpus schema version should be 1");
invariant(
  Array.isArray(corpus?.vectors) && corpus.vectors.length > 0,
  "corpus should have vectors",
);
for (const result of [
  "accepted",
  "descriptor_invalid",
  "invalid_dimensions",
  "dimensions_out_of_range",
]) {
  invariant(
    corpus.vectors.some((vector) => vector.expected === result),
    "corpus should exercise " + result,
  );
}

const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const schemaHash = sha256(schemaText);
const corpusHash = sha256(corpusText);
