function stripTypeMarkers(source) {
  return source
    .replaceAll("/*EXPORT_CLASSIFIER*/ ", "")
    .replaceAll("/*EXPORT_DESCRIPTOR_CLASSIFIER*/ ", "")
    .replace(/\/\*:[^*]+\*\//g, "");
}

function applyTypeMarkers(source) {
  return source
    .replaceAll("/*EXPORT_CLASSIFIER*/ ", "export ")
    .replaceAll("/*EXPORT_DESCRIPTOR_CLASSIFIER*/ ", "export ")
    .replace(/\/\*:([^*]+)\*\//g, ":$1");
}

